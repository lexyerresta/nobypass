// Builds site/demo-data.js from the fixtures by running the real checker on them.
// Usage: npm run site:demo   (CI fails if the committed file is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runCheck } from '../dist/index.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fixtures = path.join(root, 'fixtures');

// One key file per stack: the file the agent "quick-fixed" and its corrected version.
const STACKS = [
  { id: 'laravel', label: 'Laravel', lang: 'php', fixture: 'laravel', file: 'app/Http/Controllers/UserController.php' },
  { id: 'symfony', label: 'Symfony', lang: 'php', fixture: 'symfony', file: 'src/Controller/UserController.php' },
  { id: 'nestjs', label: 'NestJS', lang: 'ts', fixture: 'nestjs', file: 'src/users/users.controller.ts' },
  { id: 'express', label: 'Express', lang: 'js', fixture: 'express', file: 'src/controllers/userController.js' },
  { id: 'nextjs', label: 'Next.js', lang: 'ts', fixture: 'nextjs', file: 'app/users/page.tsx' },
  { id: 'django', label: 'Django', lang: 'py', fixture: 'django', file: 'users/views.py' },
  { id: 'fastapi', label: 'FastAPI', lang: 'py', fixture: 'fastapi', file: 'app/routers/users.py' },
  { id: 'spring', label: 'Spring Boot', lang: 'java', fixture: 'spring', file: 'src/main/java/com/acme/shop/controller/UserController.java' },
];

function snapshot(dir, file) {
  const result = runCheck({ cwd: dir });
  if (result.error) throw new Error(`${dir}: ${result.error}`);
  const fresh = result.findings.filter((f) => f.status === 'new');
  const pick = (f) => ({
    rule: f.ruleId,
    severity: f.severity,
    line: f.line,
    file: f.file,
    evidence: f.evidence,
    expected: f.expected,
    fix: f.suggestion,
  });
  return {
    code: fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n').trimEnd(),
    findings: fresh.filter((f) => f.file === file).map(pick),
    others: fresh.filter((f) => f.file !== file).map((f) => ({ rule: f.ruleId, severity: f.severity, file: f.file, line: f.line })),
    summary: {
      files: result.filesAnalyzed,
      errors: fresh.filter((f) => f.severity === 'error').length,
      warnings: fresh.filter((f) => f.severity === 'warning').length,
      blocking: fresh.filter((f) => f.blocking).length,
      exitCode: result.exitCode,
    },
  };
}

const data = STACKS.map((s) => ({
  id: s.id,
  label: s.label,
  lang: s.lang,
  file: s.file,
  bad: snapshot(path.join(fixtures, `${s.fixture}-violations`), s.file),
  good: snapshot(path.join(fixtures, `${s.fixture}-valid`), s.file),
}));

for (const d of data) {
  if (d.bad.summary.exitCode !== 1 || d.good.summary.exitCode !== 0) {
    throw new Error(`${d.id}: expected violations to fail and the fix to pass`);
  }
}

const out = `// Generated by scripts/build-site-demo.mjs from fixtures/ with the real checker. Do not edit.\nwindow.NOBYPASS_DEMO = ${JSON.stringify(data, null, 1)};\n`;
fs.writeFileSync(path.join(root, 'site', 'demo-data.js'), out);
console.log(`site/demo-data.js: ${data.length} stacks, ${data.reduce((n, d) => n + d.bad.findings.length + d.bad.others.length, 0)} findings`);
